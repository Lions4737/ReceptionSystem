import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {randomUUID} from 'node:crypto';
const base=process.env.TEST_URL;
test('経験者卓の設定料金によるリエントリーと再参加時の名前固定', {skip:process.env.TEST_ISOLATED!=='1'||!base},async()=>{
 function client(){const cookies=new Map();return async(path,body,method)=>{const r=await fetch(base+path,{method:method??(body?'POST':'GET'),headers:{Origin:base,'Content-Type':'application/json',Cookie:[...cookies.values()].join('; ')},body:body&&JSON.stringify({op:randomUUID(),...body})});for(const c of r.headers.getSetCookie()){const v=c.split(';')[0];cookies.set(v.split('=')[0],v);}return {status:r.status,data:await r.json()};};}
 const admin=client(),player=client(),beginner=client();
 const key=readFileSync('.dev.vars','utf8').match(/SETUP_KEY="?([^"\n]+)"?/)[1];
 assert.equal((await admin('/api/login',{key})).status,200);
 const slug='reentry-'+randomUUID(),api='/event/'+slug+'/api/';
 assert.equal((await admin('/api/events',{slug,name:'リエントリー検証'})).status,201);
 assert.equal((await admin('/api/events',{slug,enabled:true},'PATCH')).status,200);
 const expert=(await admin(api+'table-config',{action:'create',name:'経験者',kind:'expert',seat_count:3})).data.table;
 const novice=(await admin(api+'table-config',{action:'create',name:'初心者',kind:'beginner',seat_count:3})).data.table;
 await player(api+'identity',{});
 assert.equal((await player(api+'join',{nickname:'最初の名前',kind:'expert'})).status,201);
 const current=async()=>(await player(api+'me')).data.tickets[0];
 const action=async(action,fields={})=>{const t=await current();return admin(api+'action',{scope:'staff',action,id:t.id,version:t.version,...fields});};
 assert.equal((await action('set-status',{status:'playing',table:expert,seat:1})).status,200);
 const before=await current();
 assert.equal((await player(api+'action',{scope:'player',action:'reentry',id:before.id,version:before.version,confirmed:true,expected_fee:300})).status,403);
 assert.equal((await action('reentry')).status,400);
 const op=randomUUID(),request={op,scope:'staff',action:'reentry',id:before.id,version:before.version,confirmed:true,expected_fee:300};
 const originalSettings=(await admin(api+'staff')).data.settings;
 assert.equal(originalSettings.reentry_fee,300);
 assert.equal((await admin(api+'settings',{...originalSettings,reentry_fee:450})).status,200);
 assert.equal((await admin(api+'action',request)).status,409);
 request.expected_fee=450;
 const revenue=(await admin(api+'staff')).data.revenue;
 assert.equal((await admin(api+'action',request)).status,200);
 assert.equal((await admin(api+'action',request)).status,200);
 let after=await current();
 for(const field of ['status','seat','table_id','started_at','ends_at','minutes','initial_chips','paused_ms','paid'])assert.equal(after[field],before[field],field);
 let snapshot=(await admin(api+'staff')).data;
 assert.equal(snapshot.revenue,revenue+450);
 assert.equal(snapshot.tickets.find(t=>t.id===before.id).reentry_count,1);
 assert.equal((await admin(api+'settings',{...originalSettings,reentry_fee:-1})).status,400);
 const audit=(await admin(api+'audit')).data.operations.find(o=>o.action==='reentry');
 assert.ok(audit);
 assert.equal(snapshot.participationStats.find(s=>s.kind==='expert').revenue,revenue+450);
 assert.equal((await action('reentry',{confirmed:true,expected_fee:450})).status,200);
 assert.equal((await admin(api+'staff')).data.revenue,revenue+900);
 const table=(await admin(api+'staff')).data.tables.find(t=>t.id===expert);
 assert.equal((await admin(api+'table',{table:expert,version:table.version})).status,200);
 const pausedBefore=await current();
 assert.equal((await action('reentry',{confirmed:true,expected_fee:450})).status,200);
 assert.equal((await current()).ends_at,pausedBefore.ends_at);
 assert.equal((await current()).started_at,pausedBefore.started_at);
 assert.equal((await action('adjust-time',{seconds:0})).status,200);
 assert.equal((await action('reentry',{confirmed:true,expected_fee:450})).status,409);
 assert.equal((await action('finish',{score:0})).status,200);
 assert.equal((await action('reentry',{confirmed:true,expected_fee:450})).status,409);
 // Another visitor may have taken the old name while this player was finished.
 const other=client();await other(api+'identity',{});
 assert.equal((await other(api+'join',{nickname:'最初の名前',kind:'expert'})).status,201);
 assert.equal((await player(api+'join',{nickname:'変えようとした名前',kind:'expert'})).status,409);
 // The original name becomes available when the other visitor cancels.
 const otherTicket=(await other(api+'me')).data.tickets[0];
 assert.equal((await other(api+'action',{scope:'player',action:'cancel',id:otherTicket.id,version:otherTicket.version})).status,200);
 assert.equal((await player(api+'join',{nickname:'変えようとした名前',kind:'expert'})).status,201);
 assert.equal((await current()).nickname,'最初の名前');
 assert.notEqual((await current()).id,before.id);
 const repeatId=(await current()).id;
 const repeatResults=await Promise.all([player(api+'join',{nickname:'最初の名前',kind:'expert'}),player(api+'join',{nickname:'最初の名前',kind:'expert'})]);
 assert.deepEqual(repeatResults.map(r=>r.status),[200,200]);
 assert.equal((await current()).id,repeatId);
 const stranger=client();await stranger(api+'identity',{});
 assert.equal((await stranger(api+'join',{nickname:'最初の名前',kind:'expert'})).status,409);
 await beginner(api+'identity',{});
 assert.equal((await beginner(api+'join',{nickname:'初心者',kind:'beginner'})).status,201);
 let b=(await beginner(api+'me')).data.tickets[0];
 assert.equal((await admin(api+'action',{scope:'staff',action:'set-status',id:b.id,version:b.version,status:'playing',table:novice,seat:1})).status,200);
 b=(await beginner(api+'me')).data.tickets[0];
 assert.equal((await admin(api+'action',{scope:'staff',action:'reentry',id:b.id,version:b.version,confirmed:true,expected_fee:300})).status,409);
});
